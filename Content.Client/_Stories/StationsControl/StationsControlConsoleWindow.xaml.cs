using Content.Client.UserInterface.Controls;
using Content.Shared._Stories.StationsControl;
using Content.Shared.AlertLevel;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._Stories.StationsControl;

[GenerateTypedNameReferences]
public sealed partial class StationsControlConsoleWindow : FancyWindow
{
    private NetEntity? _selectedStation;
    private ProtoId<AlertLevelPrototype>? _selectedAlertLevel;
    private List<ProtoId<AlertLevelPrototype>> _allowedAlertLevels = new();
    private bool _allowAnyAlertLevel;
    private bool _countdownStarted;
    private TimeSpan? _countdownEnd;
    private TimeSpan? _setAlertLevelUnlock;

    private static readonly TimeSpan SetAlertLevelCooldown = TimeSpan.FromSeconds(5);

    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IPrototypeManager _protoManager = default!;
    [Dependency] private IGameTiming _gameTiming = default!;

    public event Action<NetEntity, string>? SetAlertLevelRequested;
    public event Action<TimeSpan>? CallEvacRequested;
    public event Action? RecallEvacRequested;

    public StationsControlConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        SetAlertLevelButton.OnPressed += _ => OnSetAlertLevelPressed();
        StationSelector.OnItemSelected += args =>
        {
            StationSelector.SelectId(args.Id);
            SelectStation(args.Id);
        };
        AlertLevelSelector.OnItemSelected += args =>
        {
            AlertLevelSelector.SelectId(args.Id);
            if (AlertLevelSelector.GetItemMetadata(args.Id) is ProtoId<AlertLevelPrototype> protoId)
                _selectedAlertLevel = protoId;
        };
        CallEvacButton.OnPressed += _ =>
        {
            if (_selectedStation == null)
                return;

            if (!TryParseEvacTime(EvacTimeInput.Text, out var countdownTime))
            {
                return;
            }

            if (countdownTime < TimeSpan.FromMinutes(2) || countdownTime > TimeSpan.FromMinutes(30))
            {
                return;
            }

            CallEvacRequested?.Invoke(countdownTime);
        };
        RecallEvacButton.OnPressed += _ =>
        {
            if (_selectedStation != null)
                RecallEvacRequested?.Invoke();
        };
    }

    public void UpdateState(StationsControlConsoleState state)
    {
        _allowedAlertLevels = state.AllowedAlertLevels;
        _allowAnyAlertLevel = state.AllowAnyAlertLevel;

        var previous = _selectedStation;
        var selectIndex = 0;
        StationSelector.Clear();

        for (var i = 0; i < state.StationsList.Count; i++)
        {
            StationSelector.AddItem(state.StationsList[i]);
            StationSelector.SetItemMetadata(i, state.StationsNetIds[i]);

            if (state.StationsNetIds[i] == previous)
                selectIndex = i;
        }

        if (StationSelector.ItemCount > 0)
        {
            StationSelector.Select(selectIndex);
            SelectStation(selectIndex);
        }
        else
        {
            _selectedStation = null;
            SetAlertLevelButton.Disabled = true;
        }

        _countdownStarted = state.ShuttleTimeLeft.HasValue;
        _countdownEnd = state.ShuttleTimeLeft.HasValue
            ? _gameTiming.CurTime + state.ShuttleTimeLeft.Value
            : null;

        UpdateCountdown();
    }

    private void SelectStation(int index)
    {
        if (index < 0 || index >= StationSelector.ItemCount)
            return;

        if (StationSelector.GetItemMetadata(index) is not NetEntity netEnt)
            return;

        _selectedStation = netEnt;
        _selectedAlertLevel = null;
        AlertLevelSelector.Clear();
        var stationUid = _entManager.GetEntity(netEnt);

        if (_entManager.TryGetComponent<AlertLevelComponent>(stationUid, out var alertComp))
        {
            foreach (var levelId in alertComp.AvailableAlertLevels)
            {
                if (!_allowAnyAlertLevel && !_allowedAlertLevels.Contains(levelId))
                    continue;

                if (!_protoManager.TryIndex(levelId, out var levelProto))
                    continue;

                AlertLevelSelector.AddItem(levelProto.LocalizedName);
                AlertLevelSelector.SetItemMetadata(AlertLevelSelector.ItemCount - 1, levelId);
            }

            if (AlertLevelSelector.ItemCount > 0)
            {
                AlertLevelSelector.Select(0);
                if (AlertLevelSelector.GetItemMetadata(0) is ProtoId<AlertLevelPrototype> levelProto)
                    _selectedAlertLevel = levelProto;
            }
            else
                SetAlertLevelButton.Disabled = true;
        }

        SetAlertLevelButton.Disabled = _selectedAlertLevel == null || _gameTiming.CurTime < _setAlertLevelUnlock;
    }

    private void UpdateCurrentAlertLevelLabel()
    {
        if (_selectedStation is not { } netEnt
            || !_entManager.TryGetEntity(netEnt, out var stationUid)
            || !_entManager.TryGetComponent<AlertLevelComponent>(stationUid.Value, out var alertComp)
            || !_protoManager.TryIndex(alertComp.CurrentAlertLevel, out var currentProto))
            return;

        CurrentAlertLevelLabel.Text = currentProto.LocalizedName;
    }

    private void OnSetAlertLevelPressed()
    {
        if (_selectedStation == null || _selectedAlertLevel == null)
            return;

        SetAlertLevelRequested?.Invoke(_selectedStation.Value, _selectedAlertLevel.Value.Id);

        _setAlertLevelUnlock = _gameTiming.CurTime + SetAlertLevelCooldown;
        SetAlertLevelButton.Disabled = true;
    }

    private bool TryParseEvacTime(string input, out TimeSpan result)
    {
        result = default;
        var parts = input.Split(':');
        if (parts.Length != 2)
            return false;
        if (!int.TryParse(parts[0], out var minutes) || !int.TryParse(parts[1], out var seconds))
            return false;
        if (minutes < 0 || seconds < 0 || seconds >= 60)
            return false;
        result = TimeSpan.FromSeconds(minutes * 60 + seconds);
        return true;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateCountdown();
        UpdateCurrentAlertLevelLabel();

        if (SetAlertLevelButton.Disabled
            && _selectedAlertLevel != null
            && _setAlertLevelUnlock != null
            && _gameTiming.CurTime >= _setAlertLevelUnlock)
        {
            _setAlertLevelUnlock = null;
            SetAlertLevelButton.Disabled = false;
        }
    }

    private void UpdateCountdown()
    {
        if (!_countdownStarted || _countdownEnd == null)
        {
            CountdownLabel.Text = "00:00";
            return;
        }

        var countdown = Math.Max(_countdownEnd.Value.Subtract(_gameTiming.CurTime).TotalSeconds, 0);
        var remainingWholeSeconds = (int)Math.Ceiling(countdown);
        var message = (remainingWholeSeconds / 60).ToString("D2") + ":" + (remainingWholeSeconds % 60).ToString("D2");
        CountdownLabel.Text = message;
    }
}